//! Generates `src/procedures.rs`: procedure names and a deep round-trip check,
//! from the elementary procedures (NGAP-PDU-Descriptions), the messages and
//! their IE sets (NGAP-PDU-Contents) and the ids (NGAP-Constants). Opaque open
//! types leave this mapping out of the bindings.

use std::collections::BTreeMap;
use std::fmt::Write;
use std::path::Path;

struct Procedure {
    name: String,
    code: u8,
    /// Message type per kind: initiating, successful, unsuccessful.
    messages: [Option<String>; 3],
}

/// `{ ... }` bodies following each line that contains `marker`, with the
/// name before the marker.
fn blocks<'a>(text: &'a str, marker: &str) -> Vec<(&'a str, &'a str)> {
    let mut out = Vec::new();
    let mut rest = text;
    while let Some(at) = rest.find(marker) {
        let line_start = rest[..at].rfind('\n').map_or(0, |i| i + 1);
        let name = rest[line_start..at].trim();
        let open = at + rest[at..].find('{').unwrap();
        let mut depth = 0;
        let mut end = open;
        for (i, c) in rest[open..].char_indices() {
            match c {
                '{' => depth += 1,
                '}' => {
                    depth -= 1;
                    if depth == 0 {
                        end = open + i;
                        break;
                    }
                }
                _ => {}
            }
        }
        out.push((name, &rest[open + 1..end]));
        rest = &rest[end..];
    }
    out
}

/// Type name as `rasn-compiler` writes it: hyphens dropped, the letter after
/// each one upper-cased (`UE-associatedLogicalNG-connectionList`).
fn rust_name(asn: &str) -> String {
    asn.split('-')
        .enumerate()
        .map(|(i, part)| {
            let mut chars = part.chars();
            match (i, chars.next()) {
                (0, _) | (_, None) => part.to_string(),
                (_, Some(first)) => first.to_uppercase().chain(chars).collect(),
            }
        })
        .collect()
}

/// Built-in types written inline in an IE set (no named binding to decode into).
const BUILT_IN: [&str; 6] = ["OCTET", "BIT", "INTEGER", "ENUMERATED", "BOOLEAN", "NULL"];

pub fn generate(asn: &Path, output: &Path, version: &str) {
    let read = |module: &str| std::fs::read_to_string(asn.join(format!("{module}.asn"))).unwrap();
    let (constants, descriptions, contents) =
        (read("NGAP-Constants"), read("NGAP-PDU-Descriptions"), read("NGAP-PDU-Contents"));

    // id-X ProcedureCode ::= N, id-Y ProtocolIE-ID ::= N
    let mut ids = BTreeMap::new();
    for line in constants.lines() {
        let words: Vec<&str> = line.split_whitespace().collect();
        if let [name, _, "::=", value] = words.as_slice()
            && name.starts_with("id-")
            && let Ok(v) = value.parse::<u32>()
        {
            ids.insert(name.to_string(), v);
        }
    }

    let mut procedures = Vec::new();
    for (name, body) in blocks(&descriptions, "NGAP-ELEMENTARY-PROCEDURE ::=") {
        let field = |key: &str| {
            body.lines().find_map(|l| l.trim().strip_prefix(key).map(|v| v.trim().to_string()))
        };
        let Some(code) = field("PROCEDURE CODE") else { continue }; // the class and the sets
        procedures.push(Procedure {
            name: name.to_string(),
            code: ids[&code] as u8,
            messages: [field("INITIATING MESSAGE"), field("SUCCESSFUL OUTCOME"), field("UNSUCCESSFUL OUTCOME")],
        });
    }
    procedures.sort_by_key(|p| p.code);

    // Msg ::= SEQUENCE { protocolIEs ProtocolIE-Container { {MsgIEs} }, ... }
    let mut message_sets = BTreeMap::new();
    for (name, body) in blocks(&contents, "::= SEQUENCE") {
        if let Some(set) = body
            .split("ProtocolIE-Container")
            .nth(1)
            .and_then(|s| s.split(['{', '}']).map(str::trim).find(|w| !w.is_empty()))
        {
            message_sets.insert(name.to_string(), set.to_string());
        }
    }
    // MsgIEs NGAP-PROTOCOL-IES ::= { { ID id-X CRITICALITY c TYPE T PRESENCE p } | ... }
    let mut sets: BTreeMap<String, Vec<(u32, String)>> = BTreeMap::new();
    for (name, body) in blocks(&contents, "NGAP-PROTOCOL-IES ::=") {
        let ies = body
            .split('{')
            .filter_map(|ie| {
                let words: Vec<&str> = ie.split_whitespace().collect();
                let id = words.iter().position(|w| *w == "ID").map(|i| words[i + 1])?;
                let ty = words.iter().position(|w| *w == "TYPE").map(|i| words[i + 1])?;
                (!BUILT_IN.contains(&ty)).then(|| (ids[id], rust_name(ty)))
            })
            .collect();
        sets.insert(name.to_string(), ies);
    }

    let mut out = String::new();
    let _ = writeln!(out, "// @generated by proto/ngap/codegen from TS 38.413 V{version}. Do not edit.\n");
    out.push_str("use crate::*;\n\n");
    out.push_str("/// Name of the elementary procedure with this code.\n");
    out.push_str("pub fn procedure_name(code: u8) -> Option<&'static str> {\n    match code {\n");
    for p in &procedures {
        let _ = writeln!(out, "        {} => Some(\"{}\"),", p.code, p.name);
    }
    out.push_str("        _ => None,\n    }\n}\n\n");

    out.push_str(
        "/// Decodes the procedure message of `pdu` and each of its IE values, re-encodes\n\
         /// each and compares with the received bytes. Returns the values checked;\n\
         /// unknown procedures and IEs (from a later release) are skipped.\n\
         pub fn check(pdu: &NGAPPDU) -> Result<usize, CheckError> {\n\
         \x20   let (kind, code, value) = match pdu {\n\
         \x20       NGAPPDU::initiatingMessage(m) => (0, m.procedure_code.0, &m.value),\n\
         \x20       NGAPPDU::successfulOutcome(m) => (1, m.procedure_code.0, &m.value),\n\
         \x20       NGAPPDU::unsuccessfulOutcome(m) => (2, m.procedure_code.0, &m.value),\n\
         \x20   };\n\
         \x20   match (kind, code) {\n",
    );
    let mut arms = 0;
    for p in &procedures {
        for (kind, message) in p.messages.iter().enumerate() {
            let Some(message) = message else { continue };
            let Some(ies) = message_sets.get(message).and_then(|set| sets.get(set)) else { continue };
            let ty = rust_name(message);
            let _ = writeln!(out, "        ({kind}, {}) => {{", p.code);
            let _ = writeln!(out, "            let message: {ty} = round_trip(\"{ty}\", value)?;");
            out.push_str("            let mut checked = 1;\n            for ie in &message.protocol_ies.0 {\n");
            out.push_str("                checked += match IeId::raw(&ie.id) {\n");
            for (id, ie_ty) in ies {
                let _ = writeln!(out, "                    {id} => round_trip::<{ie_ty}>(\"{ie_ty}\", &ie.value).map(|_| 1)?,");
            }
            out.push_str("                    _ => 0,\n                };\n            }\n            Ok(checked)\n        }\n");
            arms += 1;
        }
    }
    out.push_str("        _ => Ok(0),\n    }\n}\n");
    std::fs::write(output, out).unwrap();
    println!("{}: {} procedures, {arms} messages", output.display(), procedures.len());
}
